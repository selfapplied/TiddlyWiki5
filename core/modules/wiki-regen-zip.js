"use strict";

/*
Get a tiddler's content, with automatic asset generation for regen-zip tiddlers
This extends the base getTiddlerText with transparent asset generation
*/
exports.getTiddlerWithGeneration = function(title) {
	var tiddler = this.getTiddler(title);
	
	if(!tiddler) {
		return null;
	}
	
	// If this is a regen-zip tiddler, ensure assets are generated
	if(tiddler.fields["regen-zip"] && $tw.regenZipVM) {
		// Check if we need to regenerate
		var cacheKey = title + ":generated";
		if(!this.getCacheForTiddler(title, "regen-zip", function() {
			return generateAndCacheTiddler(title, tiddler);
		})) {
			// Cache miss, generate now
			generateAndCacheTiddler(title, tiddler);
		}
	}
	
	return tiddler;
};

/*
Check if a tiddler has regen-zip capabilities
*/
exports.isRegenZipTiddler = function(title) {
	var tiddler = this.getTiddler(title);
	return tiddler && (
		tiddler.fields["regen-zip"] || 
		tiddler.fields.generator ||
		tiddler.fields.seed
	);
};

/*
Get all assets generated by a regen-zip tiddler
*/
exports.getGeneratedAssets = function(title) {
	if(!$tw.regenZipCache || !$tw.regenZipCache[title]) {
		// Try to generate if not cached
		this.generateAssets(title);
	}
	
	var cached = $tw.regenZipCache[title];
	return cached ? cached.assets : null;
};

/*
Get metadata for generated assets
*/
exports.getGenerationMetadata = function(title) {
	if(!$tw.regenZipCache || !$tw.regenZipCache[title]) {
		return null;
	}
	
	return $tw.regenZipCache[title].metadata;
};

/*
Force regeneration of assets for a tiddler
*/
exports.regenerateTiddler = function(title) {
	// Clear cache
	if($tw.regenZipCache && $tw.regenZipCache[title]) {
		delete $tw.regenZipCache[title];
	}
	
	// Clear tiddler cache
	this.clearCache(title);
	
	// Regenerate
	return this.generateAssets(title);
};

/*
Get all tiddlers that use regen-zip
*/
exports.getRegenZipTiddlers = function() {
	var self = this;
	var titles = [];
	
	this.each(function(tiddler, title) {
		if(tiddler.fields["regen-zip"]) {
			titles.push(title);
		}
	});
	
	return titles;
};

/*
Get statistics about regen-zip usage in the wiki
*/
exports.getRegenZipStatistics = function() {
	var stats = {
		totalTiddlers: 0,
		generators: {},
		seeds: {},
		zp35Signatures: {},
		cachedAssets: 0,
		totalAssets: 0
	};
	
	var self = this;
	
	this.each(function(tiddler, title) {
		if(tiddler.fields["regen-zip"]) {
			stats.totalTiddlers++;
			
			var generator = tiddler.fields.generator;
			if(generator) {
				stats.generators[generator] = (stats.generators[generator] || 0) + 1;
			}
			
			var seed = tiddler.fields.seed;
			if(seed) {
				stats.seeds[seed] = (stats.seeds[seed] || 0) + 1;
			}
			
			var zp35 = tiddler.fields.zp35;
			if(zp35) {
				stats.zp35Signatures[zp35] = (stats.zp35Signatures[zp35] || 0) + 1;
			}
			
			// Check cache
			if($tw.regenZipCache && $tw.regenZipCache[title]) {
				stats.cachedAssets++;
				var cached = $tw.regenZipCache[title];
				if(cached.assets) {
					stats.totalAssets += cached.assets.length;
				}
			}
		}
	});
	
	return stats;
};

/*
Verify ZP35 signatures for all regen-zip tiddlers
*/
exports.verifyRegenZipSignatures = function() {
	if(!$tw.zp35Operator) {
		return {
			error: "ZP35 operator not available"
		};
	}
	
	var results = [];
	var self = this;
	
	this.each(function(tiddler, title) {
		if(tiddler.fields.zp35) {
			var result = $tw.zp35Operator.verifySignature(tiddler, tiddler.fields.zp35);
			results.push({
				title: title,
				valid: result.valid,
				computed: result.computed,
				expected: result.expected,
				distance: result.distance,
				message: result.message
			});
		}
	});
	
	return results;
};

/*
Find semantically similar tiddlers using ZP35
*/
exports.findSimilarTiddlers = function(title, maxDistance) {
	if(!$tw.zp35Operator) {
		return [];
	}
	
	maxDistance = maxDistance || $tw.zp35Operator.kappa;
	
	var sourceTiddler = this.getTiddler(title);
	if(!sourceTiddler) {
		return [];
	}
	
	var similar = [];
	var self = this;
	
	this.each(function(tiddler, targetTitle) {
		if(targetTitle !== title) {
			var coherence = $tw.zp35Operator.checkCoherence(sourceTiddler, tiddler);
			if(coherence.distance !== null && coherence.distance < maxDistance) {
				similar.push({
					title: targetTitle,
					distance: coherence.distance,
					mode: coherence.mode,
					confidence: coherence.confidence
				});
			}
		}
	});
	
	// Sort by distance
	similar.sort(function(a, b) {
		return a.distance - b.distance;
	});
	
	return similar;
};

/*
Batch regenerate all regen-zip tiddlers
*/
exports.regenerateAll = function(options) {
	options = options || {};
	var results = {
		success: 0,
		failed: 0,
		skipped: 0,
		errors: []
	};
	
	var titles = this.getRegenZipTiddlers();
	var self = this;
	
	titles.forEach(function(title) {
		try {
			var result = self.regenerateTiddler(title);
			if(result && result.success) {
				results.success++;
			} else {
				results.failed++;
				results.errors.push({
					title: title,
					error: result ? result.error : "Unknown error"
				});
			}
		} catch(e) {
			results.failed++;
			results.errors.push({
				title: title,
				error: e.message
			});
		}
	});
	
	return results;
};

/*
Helper function to generate and cache tiddler assets
*/
function generateAndCacheTiddler(title, tiddler) {
	if(!$tw.regenZipVM) {
		return null;
	}
	
	var vm = $tw.regenZipVM;
	vm.reset();
	
	if(vm.load(tiddler)) {
		var result = vm.run();
		if(result.success) {
			// Store in global cache
			$tw.regenZipCache = $tw.regenZipCache || {};
			$tw.regenZipCache[title] = {
				assets: result.assets,
				metadata: result.metadata,
				timestamp: Date.now()
			};
			return result;
		}
	}
	
	return null;
}
